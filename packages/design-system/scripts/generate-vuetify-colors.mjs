import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const colorsPath = new URL('../colors.css', import.meta.url)
const outputPath = new URL('../vuetify-colors.ts', import.meta.url)
const check = process.argv.includes('--check')
const source = await readFile(colorsPath, 'utf8')
const colorDeclarations = [
  ...source.matchAll(
    /^\s*--hs-([a-z0-9-]+):\s*(#[0-9a-f]{6}(?:[0-9a-f]{2})?);$/gim
  ),
]

if (colorDeclarations.length === 0) {
  throw new Error(
    `No --hs-* color declarations found in ${fileURLToPath(colorsPath)}`
  )
}

const colors = colorDeclarations.map(([, name, value]) => {
  const property = /^[a-z][a-z0-9]*$/.test(name) ? name : `'${name}'`
  return `  ${property}: '${value}',`
})
const output = [
  '// Generated from colors.css by scripts/generate-vuetify-colors.mjs.',
  '// Do not edit this file directly.',
  'export const vuetifyColors = {',
  ...colors,
  '} as const',
  '',
].join('\n')

if (check) {
  const existing = await readFile(outputPath, 'utf8')
  if (existing !== output) {
    throw new Error(
      `${fileURLToPath(outputPath)} is out of date. Run npm run generate:vuetify-colors --workspace @hydroserver/design-system.`
    )
  }
} else {
  await writeFile(outputPath, output)
}
